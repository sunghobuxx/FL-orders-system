// @vitest-environment jsdom
import { act, renderHook, waitFor, cleanup } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
const m = vi.hoisted(() => ({ get: vi.fn(), focus: null, active: null }));
vi.mock('../../driver-mobile/lib/api', () => ({ apiGet: m.get }));
vi.mock('../../driver-mobile/node_modules/expo-router', () => ({ useFocusEffect: (cb) => { m.focus = cb; } }));
vi.mock('../../driver-mobile/node_modules/react-native', () => ({ Alert: { alert: vi.fn() }, AppState: { currentState: 'active', addEventListener: (_, cb) => { m.active = cb; return { remove: vi.fn() }; } } }));
import { useDriverResource } from '../../driver-mobile/hooks/useDriverResource';
afterEach(cleanup);
beforeEach(() => { vi.clearAllMocks(); });
it('retains visible data on refocus and deduplicates resume requests', async () => {
    m.get.mockResolvedValueOnce({ value: 1 });
    const { result } = renderHook(() => useDriverResource('/one', 'test'));
    let blur;
    act(() => { blur = m.focus(); });
    await waitFor(() => expect(result.current.data?.value).toBe(1));
    let complete;
    m.get.mockImplementationOnce(() => new Promise(resolve => { complete = resolve; }));
    act(() => { blur(); blur = m.focus(); });
    expect(result.current.loading).toBe(false);
    expect(result.current.data?.value).toBe(1);
    act(() => { m.active('active'); m.active('active'); });
    expect(m.get).toHaveBeenCalledTimes(2);
    await act(async () => { complete({ value: 2 }); });
    expect(result.current.data?.value).toBe(2);
    act(() => blur());
});
it('cancels hidden requests and rejects late responses from an older date', async () => {
    let finishOld;
    m.get.mockImplementationOnce(() => new Promise(resolve => { finishOld = resolve; }));
    const { result, rerender } = renderHook(({ path }) => useDriverResource(path, 'test'), { initialProps: { path: '/old' } });
    let blur;
    act(() => { blur = m.focus(); });
    const signal = m.get.mock.calls[0][1];
    act(() => blur());
    expect(signal.aborted).toBe(true);
    rerender({ path: '/new' });
    m.get.mockResolvedValueOnce({ value: 'new' });
    act(() => { blur = m.focus(); });
    await waitFor(() => expect(result.current.data).toEqual({ value: 'new' }));
    await act(async () => { finishOld({ value: 'old' }); });
    expect(result.current.data).toEqual({ value: 'new' });
    act(() => blur());
});
it('does not let an old refresh overwrite an optimistic confirmation', async () => {
    m.get.mockResolvedValueOnce({ checked: false });
    const { result } = renderHook(() => useDriverResource('/one', 'test'));
    let blur;
    act(() => { blur = m.focus(); });
    await waitFor(() => expect(result.current.data).toEqual({ checked: false }));
    let complete;
    m.get.mockImplementationOnce(() => new Promise(resolve => { complete = resolve; }));
    act(() => { void result.current.refresh(); });
    const signal = m.get.mock.calls[1][1];
    act(() => result.current.mutate(() => ({ checked: true })));
    expect(signal.aborted).toBe(true);
    await act(async () => { complete({ checked: false }); });
    expect(result.current.data?.checked).toBe(true);
    act(() => blur());
});
